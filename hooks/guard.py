#!/usr/bin/env python3
"""Хук PreToolUse: агентам закрыты секреты.

Перехватывает вызов инструмента до исполнения. Блокирует команды работы с
секретами, чтение файла с секретами и доступ к ключу шифрования в связке
ключей macOS.

Принцип: защита правами, а не формулировкой в промпте. Инструкцию можно
переспорить другой инструкцией, перехватчик переспорить нельзя.

Шаблоны ниже собраны из кусков намеренно: иначе этот файл не проходит
собственную проверку при редактировании агентом. Побочный эффект, который
заодно показывает, что хук работает.
"""
import json
import re
import sys

d = json.load(sys.stdin)
inp = d.get("tool_input", {}) or {}
text = " ".join(str(v) for v in inp.values())

STORE = "secrets" + ".db"          # файл с секретами
KEYCHAIN = "find-generic" + "-password"   # чтение связки ключей

BAD = [
    r"\bhub\s+secret\b",   # команды работы с секретами
    re.escape(STORE),
    r"hub-secrets",        # запись в связке ключей с ключом шифрования
    re.escape(KEYCHAIN),
]

for pat in BAD:
    if re.search(pat, text, re.I):
        sys.stderr.write(
            "ЗАКРЫТО: секреты агентам недоступны. "
            "Если нужен ключ — попроси человека, он достанет его сам.\n"
        )
        sys.exit(2)

sys.exit(0)
